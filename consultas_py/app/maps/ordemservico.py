SQL_DAVS = (
    "SELECT D.DAVNUMERO, D.DAVEMISSAO, D.DAVTOTALLIQUIDO "
    "FROM OSDAV OD "
    "JOIN DAV D ON D.EMPCODIGO = OD.EMPCODIGO AND D.DAVCONTADOR = OD.DAVCONTADOR "
    "WHERE OD.EMPCODIGO = :EMPCODIGO AND OD.OSCONTADOR = :OSCONTADOR ORDER BY D.DAVNUMERO"
)

